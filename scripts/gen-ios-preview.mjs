#!/usr/bin/env node
// Generates apps/ios/Flowd/Core/Preview/PreviewHeroes.swift: a handful of hero rows of the demo world (Maya, Lumi, a live bounty, posts, a submission,
// money rows, a payout, an offer, a notification ...) embedded as JSON, so SwiftUI previews and view tests always have real, schema-valid data without
// touching the bundle. The rows come straight from packages/contract/fixtures, so they are the same ids the whole app uses.
//
//   node scripts/gen-ios-preview.mjs            write the file
//   node scripts/gen-ios-preview.mjs --check    exit 1 when the file is stale (CI)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fixtures = path.join(root, "packages/contract/fixtures");
const dest = path.join(root, "apps/ios/Flowd/Core/Preview/PreviewHeroes.swift");
const checkOnly = process.argv.includes("--check");

const rows = (name) => JSON.parse(fs.readFileSync(path.join(fixtures, `${name}.json`), "utf8"));
const pick = (name, id) => {
  const row = rows(name).find((r) => r.id === id);
  if (!row) throw new Error(`gen-ios-preview: ${name}.json has no row ${id}`);
  return row;
};

const HEROES = [
  // [swift property, Swift type, fixture, id]
  ["creator", "Creator", "creators", "cr_maya"],
  ["user", "User", "users", "usr_maya"],
  ["brand", "Brand", "brands", "br_lumi"],
  ["app", "BrandApp", "apps", "app_lumi"],
  ["bounty", "Bounty", "bounties", "bnty_lumi_glowup"],
  ["starterBounty", "Bounty", "bounties", "bnty_flowd_starter_1"],
  ["livePost", "Post", "posts", "post_0418"],
  ["clearedPost", "Post", "posts", "post_0384"],
  ["paidPost", "Post", "posts", "post_0293"],
  ["approvedSubmission", "Submission", "submissions", "sub_0664"],
  ["inReviewSubmission", "Submission", "submissions", "sub_0685"],
  ["changesSubmission", "Submission", "submissions", "sub_0646"],
  ["rejectedSubmission", "Submission", "submissions", "sub_0644"],
  ["clearedMoneyRow", "MoneyClockRow", "money_clock", "mc_0208"],
  ["pendingMoneyRow", "MoneyClockRow", "money_clock", "mc_0209"],
  ["scheduledPayout", "Payout", "payouts", "pay_0330"],
  ["inTransitPayout", "Payout", "payouts", "pay_0292"],
  ["offer", "Offer", "offers", "offer_0033"],
  ["notification", "AppNotification", "notifications", "ntf_0125"],
  ["scorecard", "BrandScorecard", "brand_scorecards", null],
];

function scorecardOfLumi() {
  const row = rows("brand_scorecards").find((r) => r.brand_id === "br_lumi");
  if (!row) throw new Error("gen-ios-preview: no scorecard for br_lumi");
  return row;
}

const tripleQuote = '"""';
const header =
  "// GENERATED by scripts/gen-ios-preview.mjs from packages/contract/fixtures. Do not edit by hand: run  node scripts/gen-ios-preview.mjs\n" +
  "// Hero rows of the demo world, embedded so previews and view tests never depend on the app bundle. Hand-written helpers live in PreviewData.swift.\n";

const out = [];
out.push(header);
out.push("import Foundation");
out.push("");
out.push("/// The hero samples of the demo world (Maya at Silver, Lumi's live bounty, a live and a cleared post, submissions in every state, money rows, payouts,");
out.push("/// an offer waiting on her, a notification). Real rows from the fixtures, decoded with the app's JSON rules. A decoding failure means the contract");
out.push("/// drifted from the embedded rows: `scripts/gen-ios-preview.mjs` regenerates them and the unit tests (`PreviewDataTests`) fail first. Only previews and");
out.push("/// tests read this; shipping code never does.");
out.push("enum PreviewHeroes {");
for (const [prop, type, fixture, id] of HEROES) {
  out.push(`    static let ${prop}: ${type} = decode(${type}.self, ${prop}JSON, "${prop}")`);
}
out.push("");
out.push("    private static func decode<T: Decodable>(_ type: T.Type, _ json: String, _ name: String) -> T {");
out.push("        do {");
out.push("            return try FlowdJSON.makeDecoder().decode(type, from: Data(json.utf8))");
out.push("        } catch {");
out.push('            preconditionFailure("PreviewHeroes.\\(name) no longer decodes: \\(error). Run node scripts/gen-ios-preview.mjs.")');
out.push("        }");
out.push("    }");
out.push("");
for (const [prop, type, fixture, id] of HEROES) {
  const row = prop === "scorecard" ? scorecardOfLumi() : pick(fixture, id);
  const json = JSON.stringify(row);
  if (json.includes(tripleQuote + "#")) throw new Error(`gen-ios-preview: ${prop} contains a raw-string terminator`);
  out.push(`    private static let ${prop}JSON: String = #${tripleQuote}`);
  out.push(json);
  out.push(`${tripleQuote}#`);
  out.push("");
}
out.push("}");
const text = out.join("\n").replace(/\n{3,}/g, "\n\n").replace(/\s+$/, "") + "\n";

const existing = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : null;
if (existing === text) {
  console.log("gen-ios-preview: PreviewHeroes.swift is up to date");
} else if (checkOnly) {
  console.log("gen-ios-preview: PreviewHeroes.swift is stale");
  process.exit(1);
} else {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, text);
  console.log(`gen-ios-preview: wrote ${path.relative(root, dest)} (${HEROES.length} heroes, ${(text.length / 1024).toFixed(1)} KB)`);
}
