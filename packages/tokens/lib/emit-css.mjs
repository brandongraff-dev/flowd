/** Theme-dependent custom properties as [name, value] pairs. */
function themeVars(t, theme) {
  const v = [];
  const sem = t.color.semantic[theme];
  for (const [k, val] of Object.entries(sem)) v.push([`--fd-${k}`, val]);

  // glass
  const g = t.glass[theme];
  for (const [i, id] of [[1, 'L1'], [2, 'L2'], [3, 'L3']]) {
    const L = g[id];
    v.push([`--fd-glass-${i}-blur`, px(L.blur)]);
    v.push([`--fd-glass-${i}-saturate`, `${Math.round(L.saturate * 100)}%`]);
    v.push([`--fd-glass-${i}-fill`, L.fill]);
    v.push([`--fd-glass-${i}-fill-media`, L.fillOverMedia]);
    v.push([`--fd-glass-${i}-sheen`, `linear-gradient(${L.sheen.angle}deg, ${L.sheen.from}, ${L.sheen.to})`]);
    v.push([`--fd-glass-${i}-rim`, `linear-gradient(${L.sheen.angle}deg, ${L.rim.from} 0%, ${L.rim.mid} 45%, ${L.rim.to} 100%)`]);
    v.push([`--fd-glass-${i}-rim-width`, px(L.rim.width)]);
    v.push([`--fd-glass-${i}-highlight`, L.highlight]);
    v.push([`--fd-glass-${i}-lowlight`, L.lowlight]);
    v.push([`--fd-glass-${i}-edge`, L.edge]);
    v.push([`--fd-glass-${i}-shadow`, shadowCss(t.elevation[theme][String(L.elevation)])]);
    v.push([`--fd-glass-${i}-solid`, L.solid]);
    if (L.scrim) v.push([`--fd-glass-${i}-scrim`, L.scrim]);
  }
  v.push(['--fd-glass-pointer-sheen', `radial-gradient(${g.pointerSheen.radius}px circle at var(--mx, 50%) var(--my, 0%), ${g.pointerSheen.color}, transparent 70%)`]);
  v.push(['--fd-glass-noise', num(g.noise)]);

  // elevation + glow
  for (const [lvl, layers] of Object.entries(t.elevation[theme])) v.push([`--fd-elevation-${lvl}`, shadowCss(layers)]);
  for (const [name, gl] of Object.entries(t.elevation.glow)) v.push([`--fd-glow-${name}`, `0 0 ${gl.blur}px ${gl.spread}px ${gl[theme]}`]);

  // aurora
  const au = t.aurora[theme];
  v.push(['--fd-aurora', auroraCss(au)]);
  v.push(['--fd-aurora-vignette', au.vignette === 'none' ? 'linear-gradient(transparent, transparent)' : au.vignette]);
  v.push(['--fd-aurora-noise', num(au.noise)]);

  // charts
  const ch = t.chart;
  ch.categorical[theme].forEach((c, i) => v.push([`--fd-chart-${i + 1}`, c]));
  ch.sequential[theme].forEach((c, i) => v.push([`--fd-chart-seq-${i + 1}`, c]));
  ch.ordinal[theme].forEach((c, i) => v.push([`--fd-chart-ord-${i + 1}`, c]));
  ch.diverging[theme].forEach((c, i) => v.push([`--fd-chart-div-${i + 1}`, c]));
  for (const [k, c] of Object.entries(ch.status[theme])) v.push([`--fd-chart-${k}`, c]);
  v.push(['--fd-chart-surface', ch.surface[theme]], ['--fd-chart-grid', ch.grid[theme]], ['--fd-chart-axis', ch.axis[theme]]);
  v.push(...legacyVars(t, theme));
  v.push(['--fd-ring', `0 0 0 ${t.spacing.layout.focusRingOffset}px var(--fd-bg), 0 0 0 ${t.spacing.layout.focusRingOffset + t.spacing.layout.focusRingWidth}px var(--fd-focus-ring)`]);
  return v;
}

const block = (selector, vars, indent = '') => `${indent}${selector} {\n${vars.map(([k, val]) => `${indent}  ${k}: ${val};`).join('\n')}\n${indent}}`;

/** Theme-independent properties. */
function rootVars(t) {
  const v = [];
  const P = t.color.primitive;
  for (const [hue, ramp] of Object.entries(P)) {
    if (typeof ramp === 'string') v.push([`--fd-${hue}`, ramp]);
    else for (const [step, hex] of Object.entries(ramp)) v.push([`--fd-${hue}-${step}`, hex]);
  }
  for (const [name, g] of Object.entries(t.gradient)) v.push([`--fd-gradient-${name}`, gradientCss(g)]);
  for (const [id, tier] of Object.entries(t.tier)) {
    if (id === 'note') continue;
    v.push([`--fd-tier-${id}`, tierGradientCss(tier)], [`--fd-tier-${id}-ink`, tier.ink], [`--fd-tier-${id}-glow`, tier.glow], [`--fd-tier-${id}-rim`, tier.rim]);
  }
  const cl = t.glass.clear;
  v.push(['--fd-glass-clear-blur', px(cl.blur)], ['--fd-glass-clear-saturate', `${Math.round(cl.saturate * 100)}%`], ['--fd-glass-clear-tint', cl.tint], ['--fd-glass-clear-dim', cl.dim],
    ['--fd-glass-clear-rim', `linear-gradient(135deg, ${cl.rim.from} 0%, ${cl.rim.mid} 45%, ${cl.rim.to} 100%)`]);
  v.push(['--fd-noise', NOISE_URL]);

  // type
  for (const [k, f] of Object.entries(t.typography.family)) {
    // next/font exposes a CSS variable (--font-geist-sans ...): prefer it, fall back to the fontsource family name
    const [first, ...rest] = f.stack.split(/,\s*(?=(?:[^"]*"[^"]*")*[^"]*$)/);
    v.push([`--fd-font-${k}`, f.cssVarHook ? `var(${f.cssVarHook}, ${first}), ${rest.join(', ')}` : f.stack]);
  }
  for (const [name, w] of Object.entries(t.typography.weight)) v.push([`--fd-weight-${name}`, String(w)]);
  for (const [name, s] of Object.entries(t.typography.scale)) {
    v.push([`--fd-text-${name}-size`, s.fluid ?? px(s.size)], [`--fd-text-${name}-lh`, String(s.lineHeight)], [`--fd-text-${name}-tracking`, `${s.tracking}em`], [`--fd-text-${name}-weight`, String(s.weight)]);
  }
  // spacing / radius / blur / layout
  for (const [k, val] of Object.entries(t.spacing.numeric)) v.push([`--fd-space-${k.replace('.', '-')}`, px(val)]);
  for (const [k, val] of Object.entries(t.spacing.named)) v.push([`--fd-space-${k}`, px(val)]);
  for (const [k, val] of Object.entries(t.radius)) if (k !== 'note') v.push([`--fd-radius-${k}`, px(val)]);
  for (const [k, val] of Object.entries(t.blur)) v.push([`--fd-blur-${k}`, px(val)]);
  const L = t.spacing.layout;
  v.push(['--fd-gutter', px(L.gutterMobile)], ['--fd-content-max', px(L.contentMax)], ['--fd-wide-max', px(L.wideMax)], ['--fd-prose-max', px(L.proseMax)],
    ['--fd-sidebar', px(L.dashboardSidebar)], ['--fd-sidebar-collapsed', px(L.dashboardSidebarCollapsed)], ['--fd-header-h', px(L.headerHeight)],
    ['--fd-tabbar-h', px(L.tabBarHeight)], ['--fd-hit', px(L.hitTarget)]);
  // motion
  for (const [k, ms] of Object.entries(t.motion.duration)) v.push([`--fd-dur-${k}`, `${ms}ms`]);
  v.push(['--fd-stagger', `${t.motion.stagger}ms`]);
  for (const [k, b] of Object.entries(t.motion.easing)) v.push([`--fd-ease-${kebab(k)}`, bezier(b)]);
  for (const [k, spec] of Object.entries(t.motion.spring)) {
    const { easing, durationMs } = springLinear(spec);
    v.push([`--fd-spring-${k}`, easing], [`--fd-spring-${k}-dur`, `${durationMs}ms`]);
  }
  v.push(['--fd-aurora-drift', `${t.aurora.drift.durationSec}s`], ['--fd-aurora-ease', t.aurora.drift.easing]);
  for (const [k, z] of Object.entries(t.zIndex)) v.push([`--fd-z-${k}`, String(z)]);
  for (const [k, bp] of Object.entries(t.breakpoints)) v.push([`--fd-bp-${k}`, px(bp)]);
  return v;
}

function themeBlock(t) {
  const d = themeVars(t, 'dark'), l = themeVars(t, 'light');
  return [
    '/* 2. Dark (default). Dark-first: no attribute, or data-theme="dark" */',
    block(':root,\n:root[data-theme="dark"]', [['color-scheme', 'dark'], ...d]),
    '',
    '/* 3. Light: explicit */',
    block(':root[data-theme="light"]', [['color-scheme', 'light'], ...l]),
    '',
    '/* 4. System light: no explicit theme + OS prefers light */',
    '@media (prefers-color-scheme: light) {',
    block(':root:not([data-theme="dark"]):not([data-theme="light"])', [['color-scheme', 'light'], ...l], '  '),
    '}',
  ].join('\n');
}

function a11yBlock(t) {
  const reduce = [];
  for (const i of [1, 2, 3]) reduce.push([`--fd-glass-${i}-blur`, '0px'], [`--fd-glass-${i}-saturate`, '100%'], [`--fd-glass-${i}-fill`, `var(--fd-glass-${i}-solid)`], [`--fd-glass-${i}-fill-media`, `var(--fd-glass-${i}-solid)`], [`--fd-glass-${i}-sheen`, 'none']);
  reduce.push(['--fd-aurora-noise', '0'], ['--fd-glass-noise', '0']);
  const contrast = [];
  for (const i of [1, 2, 3]) contrast.push([`--fd-glass-${i}-rim`, 'linear-gradient(135deg, var(--fd-rim-strong), var(--fd-rim-strong))'], [`--fd-glass-${i}-edge`, 'var(--fd-rim-strong)']);
  const motion = [];
  for (const k of Object.keys(t.motion.duration)) motion.push([`--fd-dur-${k}`, '1ms']);
  motion.push(['--fd-stagger', '0ms']);
  for (const k of Object.keys(t.motion.spring)) motion.push([`--fd-spring-${k}`, 'linear(0, 1)'], [`--fd-spring-${k}-dur`, '1ms']);
  return [
    '/* 5. Accessibility. `:root:root:root` out-ranks the theme blocks above (0,3,0). */',
    '@media (prefers-reduced-transparency: reduce) {',
    block(':root:root:root', reduce, '  '),
    '}',
    block(':root:root:root[data-transparency="reduce"]', reduce),
    '@media (prefers-contrast: more) {',
    block(':root:root:root', contrast, '  '),
    '}',
    '@media (prefers-reduced-motion: reduce) {',
    block(':root:root:root', motion, '  '),
    '}',
  ].join('\n');
}

function tailwindBlock(t) {
  const L = [];
  const sem = Object.keys(t.color.semantic.dark);
  L.push('  /* Default Tailwind palette removed on purpose: product code uses semantic colours only. */');
  L.push('  --color-*: initial;', '  --color-white: #ffffff;', '  --color-black: #000000;');
  for (const k of sem) L.push(`  --color-${k}: var(--fd-${k});`);
  L.push('  --color-canvas: var(--fd-bg);');
  L.push('', '  /* Legacy utility names the web app already uses (bg-canvas-raised, bg-surface-solid, text-fg-on-accent, ring-focus, text-azure, text-lagoon, shadow-glass, shadow-pop) */');
  L.push('  --color-canvas-raised: var(--fd-bg-elevated);', '  --color-surface-solid: var(--fd-surface);', '  --color-fg-on-accent: var(--fd-fg-inverse);', '  --color-focus: var(--fd-focus-ring);', '  --color-azure: var(--fd-accent);', '  --color-lagoon: var(--fd-info);');
  L.push('', '  --font-display: var(--fd-font-display);', '  --font-sans: var(--fd-font-text);', '  --font-mono: var(--fd-font-mono);');
  L.push('', '  --spacing: 0.25rem;');
  L.push('', '  /* Radius, text, shadow and easing keep Tailwind extra defaults (xs, 4xl, text-xl ...) but our names win. */');
  for (const [k, val] of Object.entries(t.radius)) if (k !== 'note') L.push(`  --radius-${k}: ${px(val)};`);
  for (const name of Object.keys(t.typography.scale)) {
    L.push(`  --text-${name}: var(--fd-text-${name}-size);`, `  --text-${name}--line-height: var(--fd-text-${name}-lh);`, `  --text-${name}--letter-spacing: var(--fd-text-${name}-tracking);`, `  --text-${name}--font-weight: var(--fd-text-${name}-weight);`);
  }
  L.push('', '  --shadow-rest: var(--fd-elevation-1);', '  --shadow-raised: var(--fd-elevation-2);', '  --shadow-float: var(--fd-elevation-3);', '  --shadow-overlay: var(--fd-elevation-4);');
  for (const name of Object.keys(t.elevation.glow)) L.push(`  --shadow-glow-${name}: var(--fd-glow-${name});`);
  L.push('  --shadow-glass: var(--fd-glass-2-shadow);', '  --shadow-pop: var(--fd-elevation-4);');
  L.push('');
  for (const k of Object.keys(t.motion.easing)) L.push(`  --ease-${kebab(k)}: var(--fd-ease-${kebab(k)});`);
  for (const k of Object.keys(t.motion.spring)) L.push(`  --ease-spring-${k}: var(--fd-spring-${k});`);
  L.push('', '  --breakpoint-*: initial;');
  for (const [k, bp] of Object.entries(t.breakpoints)) L.push(`  --breakpoint-${k}: ${px(bp)};`);
  return `@theme inline {\n${L.join('\n')}\n}`;
}

export function emitTailwindCss(t) {
  return `${HEADER('Tailwind v4 theme')}/* Only needed if you import tokens.css elsewhere: tokens.css already contains this block. */\n${tailwindBlock(t)}\n`;
}

export function emitTokensCss(t) {
  return [
    HEADER('design tokens'),
    '/* Usage: import this file once (after `@import "tailwindcss"`).',
    ' * Raw tokens are `--fd-*` and are theme-aware. Tailwind utilities (`bg-surface`, `text-fg-muted`, `text-mint`, `border-rim`, `font-display`)',
    ' * come from the `@theme inline` block at the bottom.',
    ' * Theme: <html data-theme="dark|light"> (omit, or "system", to follow the OS; default is dark when the OS has no preference). */',
    '',
    '/* 1. Primitives, scales and motion (theme independent) */',
    block(':root', rootVars(t)),
    '',
    themeBlock(t),
    '',
    a11yBlock(t),
    '',
    '/* 6. Tailwind v4 theme: semantic names only */',
    tailwindBlock(t),
    '',
  ].join('\n');
}

