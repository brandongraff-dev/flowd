// Builds supabase/tests/seed-full/full-world.test.sql: assertions about the database AFTER supabase/seed.full.sql, with every expected number computed from
// the contract fixtures (never typed by hand), so the test can only pass if the database holds exactly the demo world the web and iOS apps show.
//
// Four groups: (1) the ledger is whole, (2) one row count per loaded table, (3) read models computed by views reproduce the fixture read models,
// (4) row level security on real data: what the three personas can see, counted from the fixtures through the policies' own rules.

import { uuidFrom } from './seed-map.mjs';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sum = (list, f) => list.reduce((a, r) => a + f(r), 0);

export function buildFullWorldTest({ rows, readFixture, world, waitlist, counts }) {
  const L = [];
  const ledger = rows.get('ledger');
  const personas = world.personas;
  const maya = personas.creator.creator_id;
  const lumi = personas.brand.brand_id;
  const lumiApp = personas.brand.app_id;
  const asUser = (userId) => `select tap.as_user_by_auth('${uuidFrom(userId)}');`;
  const eq = (label, expr, want) => `select tap.eq(${q(label)}, (${expr})::text, ${q(want)});`;

  L.push(`-- flowd tests: the full demo world (supabase/seed.full.sql). GENERATED by supabase/tools/gen-seed.mjs: do not edit.
-- Run with the full seed loaded:  node supabase/tools/verify-pglite.mjs --seed-file seed.full.sql   or   sh supabase/tools/test-psql.sh --seed-full
-- Every expected number below is computed from packages/contract/fixtures by the generator.
begin;
`);

  // 1. the ledger
  L.push('-- 1. the ledger is whole: balanced transactions, escrow reconciled with every bounty, no negative floors (also proven by the deferred triggers at COMMIT)');
  L.push(`select tap.ok('audit_ledger is clean after the full seed', (public.audit_ledger() ->> 'ok')::boolean);`);
  L.push(eq('ledger legs / transactions / accounts', `select (select count(*) from public.ledger) || '/' || (select count(*) from public.ledger_transactions) || '/' || (select count(*) from public.ledger_balances)`,
    `${ledger.length}/${rows.get('ledger_transactions').length}/${new Set(ledger.map((l) => l.account)).size}`));
  L.push(eq('the ledger nets to zero across all accounts', 'select coalesce(sum(amount_cents), 0) from public.ledger', '0'));
  const wallets = rows.get('brands').reduce((a, b) => a + (b.wallet_balance_cents ?? 0), 0);
  L.push(eq('brand wallet balances (fixtures) equal the wallet accounts on the ledger', `select coalesce(sum(amount_cents), 0) from public.ledger where account like 'wallet:%'`, String(wallets)));
  L.push('');

  // 2. counts
  L.push('-- 2. one row count per loaded table');
  const tableCounts = Object.entries(counts).sort(([a], [b]) => a.localeCompare(b));
  L.push(`select tap.eq('every loaded table holds exactly its fixture rows', (select string_agg(t || '=' || n, ', ' order by t) from (values`);
  L.push(tableCounts.map(([t], i) => `  ${i ? ',' : ' '} (${q(t)}, (select count(*) from public.${t}))`).join('\n'));
  L.push(`) as c(t, n)), ${q(tableCounts.map(([t, n]) => `${t}=${n}`).join(', '))});`);
  L.push('');

  // 3. read models
  L.push('-- 3. read models computed by views reproduce the fixture read models');
  L.push(eq('the demo world is dated 2026-10-03', `select to_char(demo_now at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') from public.world`, world.now));
  L.push(eq('v_waitlist_totals reproduces the waitlist (creators / brands / invites accepted)', `select creators || '/' || brands || '/' || invites_accepted from public.v_waitlist_totals`,
    `${waitlist.leaders.filter((l) => l.kind === 'creator').length + waitlist.fillCreators}/${waitlist.leaders.filter((l) => l.kind === 'brand').length + waitlist.fillBrands}/${waitlist.invitesAccepted}`));
  L.push(eq('v_waitlist_leaders reproduces the top five (handle and referrals)', `select string_agg(handle || ':' || referrals, ',' order by position) from (select * from public.v_waitlist_leaders order by position limit 5) x`,
    waitlist.leaders.slice(0, 5).map((l) => `${l.handle}:${l.referrals_count}`).join(',')));
  const paid = rows.get('payouts').filter((p) => p.status === 'paid');
  L.push(eq('v_ticker_totals: paid payouts and what they paid', `select payouts_count || '/' || total_paid_cents from public.v_ticker_totals`, `${paid.length}/${sum(paid, (p) => p.net_cents)}`));
  const byStatus = (table, col, status) => rows.get(table).filter((r) => r[col] === status).length;
  L.push(eq('bounties by status: live / settled / draft', `select (select count(*) from public.bounties where status = 'live') || '/' || (select count(*) from public.bounties where status = 'settled') || '/' || (select count(*) from public.bounties where status = 'draft')`,
    `${byStatus('bounties', 'status', 'live')}/${byStatus('bounties', 'status', 'settled')}/${byStatus('bounties', 'status', 'draft')}`));
  L.push(eq('posts by status: live / window_closed / cleared / paid', `select (select count(*) from public.posts where status = 'live') || '/' || (select count(*) from public.posts where status = 'window_closed') || '/' || (select count(*) from public.posts where status = 'cleared') || '/' || (select count(*) from public.posts where status = 'paid')`,
    ['live', 'window_closed', 'cleared', 'paid'].map((s) => byStatus('posts', 'status', s)).join('/')));
  const mayaRow = rows.get('creators').find((c) => c.id === maya);
  L.push(eq(`${maya}: tier, lifetime cleared, approved of decided`, `select tier || '/' || lifetime_cleared_cents || '/' || approved_count || '/' || decided_count from public.creators where id = ${q(maya)}`,
    `${mayaRow.tier}/${mayaRow.lifetime_cleared_cents}/${mayaRow.approved_count}/${mayaRow.decided_count}`));
  const hourly = rows.get('post_metrics_hourly');
  L.push(eq('post_metrics_hourly rows land in their monthly partitions', `select count(*) from public.post_metrics_hourly`, String(hourly.length)));
  L.push('');

  // 4. RLS on the real world
  const own = (table, key, id) => rows.get(table).filter((r) => r[key] === id).length;
  const lumiLedger = ledger.filter((l) => l.brand_id === lumi && (l.account.startsWith('wallet:') || l.account.startsWith('escrow:'))).length;
  L.push('-- 4. row level security on the full world (the real roles; the numbers are what each persona may see by the policies of 0002_rls.sql)');
  L.push(asUser(personas.creator.user_id) + `            -- ${maya}`);
  L.push(eq('the creator sees only her own Money Clock rows', 'select count(*) from public.money_clock', String(own('money_clock', 'creator_id', maya))));
  L.push(eq('the creator sees only her own creator-account ledger legs', 'select count(*) from public.ledger', String(ledger.filter((l) => l.account === `creator:${maya}`).length)));
  L.push(eq('the creator sees her submissions, posts and payouts', `select (select count(*) from public.submissions) || '/' || (select count(*) from public.posts) || '/' || (select count(*) from public.payouts)`,
    `${own('submissions', 'creator_id', maya)}/${own('posts', 'creator_id', maya)}/${own('payouts', 'creator_id', maya)}`));
  L.push(eq('the creator sees exactly one creators row (her own) and no brands', `select (select count(*) from public.creators) || '/' || (select count(*) from public.brands)`, '1/0'));
  L.push(eq('the creator never sees conversions, API keys or RevenueCat events', `select (select count(*) from public.conversions) || '/' || (select count(*) from public.api_keys) || '/' || (select count(*) from public.revenuecat_events)`, '0/0/0'));
  L.push('select tap.as_owner();');
  L.push(asUser(personas.brand.user_id) + `            -- ${lumi}`);
  L.push(eq('the brand member sees one workspace and its one app', `select (select count(*) from public.brands) || '/' || (select count(*) from public.apps)`, '1/1'));
  L.push(eq('the brand member sees the wallet and escrow legs of the workspace, not creator or platform legs', 'select count(*) from public.ledger', String(lumiLedger)));
  L.push(eq('the brand member sees the submissions, posts, conversions and RevenueCat events of the app', `select (select count(*) from public.submissions) || '/' || (select count(*) from public.posts) || '/' || (select count(*) from public.conversions) || '/' || (select count(*) from public.revenuecat_events)`,
    `${own('submissions', 'brand_id', lumi)}/${own('posts', 'brand_id', lumi)}/${own('conversions', 'app_id', lumiApp)}/${own('revenuecat_events', 'app_id', lumiApp)}`));
  L.push(eq('the brand member sees no Money Clock and no payouts', `select (select count(*) from public.money_clock) || '/' || (select count(*) from public.payouts)`, '0/0'));
  L.push('select tap.as_owner();');
  L.push(asUser(personas.admin.user_id) + '            -- Ops');
  L.push(eq('Ops sees every ledger leg, creator and brand', `select (select count(*) from public.ledger) || '/' || (select count(*) from public.creators) || '/' || (select count(*) from public.brands)`,
    `${ledger.length}/${rows.get('creators').length}/${rows.get('brands').length}`));
  L.push('select tap.as_owner();');
  L.push('select tap.as_anon();');
  L.push(`select tap.ok('the public can read the public bounty feed and the waitlist leaders', (select count(*) from public.v_public_bounties) > 0 and (select count(*) from public.v_waitlist_leaders) = 25);`);
  L.push(`select tap.raises('the public cannot read the ledger', 'select count(*) from public.ledger', '42501');`);
  L.push(`select tap.raises('the public cannot read users', 'select count(*) from public.users', '42501');`);
  L.push('select tap.as_owner();');
  L.push('');
  L.push(`select 'seed-full/full-world.test.sql: passed' as result;
rollback;
`);
  return L.join('\n');
}
