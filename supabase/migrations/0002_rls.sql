-- flowd 0002: row-level security, grants and auth plumbing
--
-- Model
--   * Roles come from public.users.role (creator | brand_member | admin). Brand members get capabilities from
--     public.brand_role_capabilities (owner, admin, reviewer, finance, viewer, client_approver); members of an agency
--     workspace inherit their role on the workspaces the agency manages (brands.agency_id).
--   * Clients (anon, authenticated) get SELECT through policies and a deliberately small set of direct writes
--     (profile and configuration edits, with COLUMN-level grants so money, tier and status columns cannot be written).
--   * Everything that moves money or changes a state machine goes through the API server using the service role and the
--     SECURITY DEFINER functions of 0003. service_role bypasses RLS; the invariants of 0001 still apply to it.
--   * Tables with no policy (ledger_balances, social_account_tokens, encrypted_secrets, idempotency_keys, inbound_events,
--     job_runs, audit_log, state_transitions, payout_runs, fraud_flags, ml_models, admin_metrics, waitlist_entries) are
--     readable by the service role only; admin screens read them through the API.
--   * Admins read everything that has any client grant (a generated "<table>_admin_select" policy at the end).
--   * Public (anon) reads go through the views of 0004 or the small public catalogues granted below.
--
-- Performance: policies call helpers as (select private.f()) so Postgres evaluates them once per statement.

-- ===========================================================================
