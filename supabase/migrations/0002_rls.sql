create or replace function public.default_art_seed(p_seed text, p_label text default null)
returns jsonb
language sql
immutable
parallel safe
as $$
  select jsonb_strip_nulls(jsonb_build_object(
    'hue_a', (abs(hashtext(p_seed)) % 360),
    'hue_b', ((abs(hashtext(p_seed)) + 40) % 360),
    'hue_c', ((abs(hashtext(p_seed)) + 190) % 360),
    'pattern', (array['orbs', 'rings'])[1 + (abs(hashtext(p_seed || 'p')) % 2)],
    'seed', abs(hashtext(p_seed || 's')),
    'label', left(p_label, 24)
  ));
$$;
grant execute on function public.default_art_seed(text, text) to anon, authenticated;

create or replace function private.current_user_id()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select u.id from public.users u where u.auth_user_id = auth.uid() and u.deleted_at is null limit 1;
$$;

create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select u.role = 'admin' and u.status = 'active' from public.users u where u.auth_user_id = auth.uid() and u.deleted_at is null limit 1), false);
$$;

create or replace function private.current_creator_id()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select c.id
  from public.creators c
  join public.users u on u.id = c.user_id
  where u.auth_user_id = auth.uid() and u.deleted_at is null and c.deleted_at is null
  limit 1;
$$;

-- Workspaces the caller belongs to (active membership), plus the workspaces an agency of theirs manages.
create or replace function private.my_brand_ids()
returns setof text
language sql
stable
security definer
set search_path = ''
as $$
  select m.brand_id
  from public.brand_members m
  join public.users u on u.id = m.user_id
  join public.brands b on b.id = m.brand_id and b.deleted_at is null
  where u.auth_user_id = auth.uid() and u.deleted_at is null and m.status = 'active'
  union
  select mb.id
  from public.brands mb
  where mb.deleted_at is null
    and mb.agency_id in (
      select m.brand_id
      from public.brand_members m
      join public.users u on u.id = m.user_id
      where u.auth_user_id = auth.uid() and u.deleted_at is null and m.status = 'active'
    );
$$;

-- Does the caller hold a capability on a workspace? (capabilities come from brand_role_capabilities)
create or replace function private.brand_can(p_brand_id text, p_capability text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.brand_members m
    join public.users u on u.id = m.user_id
    join public.brand_role_capabilities c on c.role = m.role
    where u.auth_user_id = auth.uid() and u.deleted_at is null
      and m.status = 'active'
      and c.capability = p_capability
      and (m.brand_id = p_brand_id or m.brand_id = (select b.agency_id from public.brands b where b.id = p_brand_id))
  );
$$;

create or replace function private.creator_tier_at_least(p_creator_id text, p_tier public.tier)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select c.tier >= p_tier from public.creators c where c.id = p_creator_id), false);
$$;

create or replace function private.my_crew_ids()
returns setof text
language sql
stable
security definer
set search_path = ''
as $$
  select cm.crew_id from public.crew_members cm where cm.creator_id = private.current_creator_id();
$$;

-- Cohort boards are visible to their members only; niche and global boards to every signed-in user.
create or replace function private.can_see_leaderboard(p_leaderboard_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.leaderboards l
    where l.id = p_leaderboard_id
      and (l.scope in ('niche', 'global')
           or exists (select 1 from public.leaderboard_entries e where e.leaderboard_id = l.id and e.creator_id = private.current_creator_id()))
  );
$$;

-- Sealed bids: a brand sees only its own bid while the auction is open. After close the auction's creator and the
-- brands that bid can see every bid (second-price outcomes are transparent to the participants).
create or replace function private.auction_bids_visible(p_auction_id text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.auctions a
    where a.id = p_auction_id
      and a.status in ('closed', 'awarded', 'no_bids')
      and (a.creator_id = private.current_creator_id()
           or exists (select 1 from public.auction_bids b where b.auction_id = a.id and b.brand_id in (select private.my_brand_ids())))
  );
$$;

