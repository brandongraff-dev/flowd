  private.can_see_leaderboard(text), private.auction_bids_visible(text)
to anon, authenticated, service_role;

-- ===========================================================================
-- 3. New auth user -> public.users (creator by default; the role comes from app_metadata, which only the server can set)
-- ===========================================================================
create or replace function private.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role public.role;
  v_name text;
  v_providers public.auth_provider[];
begin
  v_role := case new.raw_app_meta_data ->> 'role'
    when 'brand_member' then 'brand_member'::public.role
    else 'creator'::public.role  -- admin is never self-assigned: Ops promote users through the admin API
  end;
  v_name := coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, 'creator'), '@', 1));
  select coalesce(array_agg(p::public.auth_provider), array['email']::public.auth_provider[])
    into v_providers
  from jsonb_array_elements_text(coalesce(new.raw_app_meta_data -> 'providers', '[]'::jsonb)) p
  where p in ('apple', 'google', 'email');
  insert into public.users (id, role, email, display_name, avatar, auth_providers, status, age_verified, locale, timezone, created_at, auth_user_id)
  values (
    public.new_id('usr'), v_role, coalesce(new.email, new.id::text || '@users.invalid'), v_name,
    public.default_art_seed(new.id::text, upper(left(v_name, 2))), v_providers, 'active', false,
    coalesce(nullif(new.raw_user_meta_data ->> 'locale', ''), 'en-US'), 'UTC', now(), new.id
  )
  on conflict do nothing;
  return new;
end
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_auth_user();

