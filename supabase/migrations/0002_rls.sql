-- 14. Admins read every table that has any client grant (writes go through the admin API, audited in audit_log)
-- ===========================================================================
do $admin$
declare
  t record;
begin
  for t in
    select c.relname
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'p') and not c.relispartition
      and has_table_privilege('authenticated', c.oid, 'select')
  loop
    execute format(
      'create policy %I on public.%I for select to authenticated using ((select private.is_admin()))',
      t.relname || '_admin_select', t.relname
    );
  end loop;
end
$admin$;

-- ===========================================================================
-- 15. Storage buckets (private) and their policies. Skipped on vanilla Postgres where the storage schema is absent.
--     Path convention: <owner id>/<file>.
-- ===========================================================================
do $storage$
begin
  if to_regclass('storage.buckets') is not null and to_regclass('storage.objects') is not null then
    insert into storage.buckets (id, name, public) values
      ('tax-docs', 'tax-docs', false),
      ('invoices', 'invoices', false),
      ('evidence', 'evidence', false),
      ('uploads', 'uploads', false)
    on conflict (id) do nothing;

    execute $p$create policy "tax_docs_owner_read" on storage.objects for select to authenticated
      using (bucket_id = 'tax-docs' and (storage.foldername(name))[1] = (select private.current_creator_id()))$p$;
    execute $p$create policy "invoices_finance_read" on storage.objects for select to authenticated
      using (bucket_id = 'invoices' and private.brand_can((storage.foldername(name))[1], 'finance.read'))$p$;
    execute $p$create policy "evidence_party_read" on storage.objects for select to authenticated
      using (bucket_id = 'evidence' and exists (select 1 from public.disputes d where d.id = (storage.foldername(name))[1]))$p$;
    execute $p$create policy "evidence_party_write" on storage.objects for insert to authenticated
      with check (bucket_id = 'evidence' and exists (select 1 from public.disputes d where d.id = (storage.foldername(name))[1]))$p$;
    execute $p$create policy "uploads_owner_read" on storage.objects for select to authenticated
      using (bucket_id = 'uploads' and (storage.foldername(name))[1] = (select private.current_creator_id()))$p$;
    execute $p$create policy "uploads_owner_write" on storage.objects for insert to authenticated
      with check (bucket_id = 'uploads' and (storage.foldername(name))[1] = (select private.current_creator_id()))$p$;
  end if;
end
$storage$;
